//! 全仓共用的基础工具。**没有业务语义**的那一类：读文本文件的规整、字节/字符串
//! 的小处理，将来可能还有路径、时间格式之类。
//!
//! # 两条约定
//!
//! **一、零外部依赖。** `Cargo.toml` 的 `[dependencies]` 现在是空的，应当保持这样。
//! 这个 crate 会被几乎所有 crate 依赖，一旦它自己拉进 serde / regex / anyhow，
//! 全仓的编译就得排在它后面，而且会诱使人把带依赖的东西也塞进来。真需要外部
//! 依赖的工具，说明它已经不属于这一层了。
//!
//! **二、进来的东西必须是「判据只此一份」的那种。** 本 crate 存在的理由是避免同
//! 一个判据被抄成好几份（见 CLAUDE.md 里 `wind-store` 为转义判据依赖 `wind-cmdbar`
//! 的先例）。只被一处用到的辅助函数留在原地，不要预先搬过来——`utils` 变成垃圾堆
//! 都是这么开始的。
//!
//! 按领域分模块（`text`、将来的 `fs` 等），不要在根上平铺一堆自由函数。

